	<h2>Доставка</h2>
	<ul class="list">
		<li>Доставка осуществляется своим транспортом и любой транспортной компанией, которая есть на территории Республики Крым.</li>
		<li>Доставка сантехники в упакованном виде осуществляется до подъезда многоквартирных домов или до ворот частных домов, где проверяется комплектность и внешний вид товара, а также соответствие модели заказу покупателя, после чего клиент должен принять товар и оплатить его подписав товарную накладную.</li>
		<li>Доставка товара осуществляется своим грузовым транспортом по всей территории Республике Крым и за пределами силами ТК.</li>
		<li>Стоимость доставки просчитывается индивидуально в зависимости от веса и объема заказа.</li>
		<li>Разгрузка и подъем товара на этаж осуществляется силами покупателя, либо обговаривается отдельно с менеджером.</li>
		<li>Покупатель обязан обеспечить беспрепятственный подъезд грузового транспорта к месту выгрузки товара, в противном случае товар доставляется до максимально возможного места подъезда грузового автомобиля.</li>
		<li>Водитель, доставляющий заказ, связывается с вами за 1 (один) час до предполагаемого времени доставки.</li>
	</ul>
