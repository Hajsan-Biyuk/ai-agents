<ul class="list">
<li>Наличный расчет - оплата в офисе компании или курьеру при получении товара;</li>
<li>Безналичный расчёт (с НДС или без НДС) – оплата товара по безналичному расчёту. После подтверждения заказа Вам высылается счёт по электронной почте;</li>
<li>Оплата кредитной или дебетовой картой - оплата в офисе компании;</li>
<li>Оплата на банковскую карту - оплата товара осуществляется переводом на карточку банка по указанным реквизитам.</li>
</ul>